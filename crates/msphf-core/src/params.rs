/// RLWE parameter pack as described in Appendix C of the City‑G spec.
#[derive(Debug, Clone, Serialize)]
pub struct RlweParamPack<'a> {
    pub n: u16,
    pub q: u16,
    pub k: u8,
    pub noise: &'a str,
    pub mont_r: u32,
    pub mont_r_inv: u32,
    pub qprime: u32,
    pub barrett_mu: u32,
    #[serde(with = "serde_bytes")]
    pub ntt_roots_fwd: &'a [u8],
    #[serde(with = "serde_bytes")]
    pub ntt_roots_inv: &'a [u8],
    pub ntt_order: &'a str,
    pub coef_endian: &'a str,
    pub hp_version: u8,
}

impl<'a> RlweParamPack<'a> {
    /// Serialise the pack to canonical CBOR bytes.
    pub fn to_cbor(&self) -> Result<Vec<u8>, MsphfError> {
        to_cbor_vec(self)
    }

    /// Compute the normative `H_L("msphf/params", [CBOR(pack)])` commitment.
    pub fn commitment(&self) -> Result<[u8; 32], MsphfError> {
        #[derive(Serialize)]
        struct Wrapper<'a>(#[serde(with = "serde_bytes")] &'a [u8]);
        let cbor = self.to_cbor()?;
        hash::h_l(ds::MSPHF_PARAMS, &Wrapper(&cbor))
    }
}

/// Default parameter pack for the RLWE A1 profile (Kyber-768 / ML-KEM).
pub fn default_pack() -> RlweParamPack<'static> {
    RlweParamPack {
        n: 256,
        q: 3329,
        k: 3,
        noise: "CBD-eta2",
        mont_r: MONT_R as u32,
        mont_r_inv: MONT_RINV as u32,
        qprime: QINV as u32,
        barrett_mu: BARRETT_MU as u32,
        ntt_roots_fwd: &NTT_ROOTS_FWD_BYTES,
        ntt_roots_inv: &NTT_ROOTS_INV_BYTES,
        ntt_order: "bitrev",
        coef_endian: "le16",
        hp_version: 1,
    }
}

/// Commitment of the default parameter pack.
pub fn default_commitment() -> Result<[u8; 32], MsphfError> {
    default_pack().commitment()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn commitment_stable_for_identical_pack() {
        let pack = RlweParamPack {
            n: 256,
            q: 3329,
            k: 3,
            noise: "CBD-eta2",
            mont_r: 1,
            mont_r_inv: 1,
            qprime: 0xFFFF_FFFF,
            barrett_mu: 0xDEAD_BEEF,
            ntt_roots_fwd: &[0u8; 512],
            ntt_roots_inv: &[0u8; 512],
            ntt_order: "bitrev",
            coef_endian: "le16",
            hp_version: 1,
        };
        let c1 = pack.commitment().expect("pack commitment");
        let c2 = pack.commitment().expect("pack commitment");
        assert_eq!(c1, c2);
    }

    #[test]
    fn default_pack_has_deterministic_commitment() {
        let c1 = default_commitment().expect("default commitment");
        let c2 = default_commitment().expect("default commitment");
        assert_eq!(c1, c2);
    }
}
